// Exports the Go engine's graded puzzle pool into src/data/bank.js.
//
//   cd engine-go && go run . pool --count 100 --replace   # grow / regrade the pool
//   npm run bank                                          # re-export for the worker
//
// Every puzzle is re-verified with the JS engine (unique solution, logic
// grade agrees) so a bad export fails loudly instead of shipping.

import { readFileSync, writeFileSync } from 'node:fs';
import { parseBoard, formatBoard } from '../src/engine/board.js';
import { search } from '../src/engine/solver.js';
import { solveLogically, LEVELS, TECHNIQUE_NAMES } from '../src/engine/logic.js';

const src = new URL('../engine-go/data/puzzles.json', import.meta.url);
const out = new URL('../src/data/bank.js', import.meta.url);

const records = JSON.parse(readFileSync(src, 'utf8'));
const bank = Object.fromEntries(LEVELS.map((l) => [l, []]));
const seen = new Set();

for (const rec of records) {
  if (rec.isDaily || !rec.technique || seen.has(rec.puzzle)) continue;
  seen.add(rec.puzzle);
  const puzzle = parseBoard(rec.puzzle);
  const { count, solution } = search(puzzle, 2);
  if (count !== 1) throw new Error(`not unique: ${rec.puzzle}`);
  const graded = solveLogically(puzzle);
  if (!graded.solved || LEVELS[graded.level] !== rec.difficulty) {
    throw new Error(`grade mismatch for ${rec.puzzle}`);
  }
  bank[rec.difficulty].push(`${rec.puzzle}${formatBoard(solution)}${graded.hardest}`);
}

const body = LEVELS.map((l) => `  ${l}: [\n${bank[l].map((e) => `    '${e}',`).join('\n')}\n  ],`).join('\n');
writeFileSync(
  out,
  `// Generated by scripts/export-bank.mjs from engine-go/data/puzzles.json. Do not edit.\n` +
    `// Entry layout: 81-char puzzle + 81-char solution + technique index.\n` +
    `export const TECHNIQUES = ${JSON.stringify(TECHNIQUE_NAMES)};\n\n` +
    `export const BANK = {\n${body}\n};\n`,
);

console.log(LEVELS.map((l) => `${l}: ${bank[l].length}`).join(', '));
